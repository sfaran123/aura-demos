  newSub,
  quickPay,
  link,
  collect,
  members,
  reports,
  settings,
  plans,
  reportPicker,
  links,
  accountant,
  daily
}

enum GuideChapter { start, desk, collection, members, reports }

extension GuideChapterLabel on GuideChapter {
  String get label => switch (this) {
        GuideChapter.start => t('מתחילים'),
        GuideChapter.desk => t('בקבלה, כל יום'),
        GuideChapter.collection => t('גבייה וחובות'),
        GuideChapter.members => t('ניהול מנויים'),
        GuideChapter.reports => t('דוחות'),
      };
}

class GuideTopic {
  const GuideTopic(this.id, this.chapter, this.title, this.when, this.steps, {this.tip, this.action, this.words = ''});
  final String id;
  final GuideChapter chapter;
  final String title;

  /// When you need this, in one sentence.
  final String when;
  final List<String> steps;
  final String? tip;
  final GuideAction? action;

  /// Extra words people might search for.
  final String words;

  bool matches(String q) {
    final parts = q.trim().toLowerCase().split(RegExp(r'\s+')).where((w) => w.length > 1);
    if (parts.isEmpty) return true;
    final hay = [title, when, ...steps, tip ?? '', words].join(' ').toLowerCase();
    return parts.every(hay.contains);
  }
}

